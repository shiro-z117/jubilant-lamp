export async function listStaff(filters: ListStaffFilters, session: Session) {
    assertAdmin(session);
    const { search, status, isActive, page, limit } = filters;

    let query = db.orm.public.Staff.where({});
    if (status) query = query.where({ status });
    if (isActive !== undefined) query = query.where({ isActive });

    if (search) {
        // the name lives on User, so find matching users first
        const pattern = likePattern(search);
        const users = await db.orm.public.User.where((u) => and(u.role.eq("staff"), u.name.ilike(pattern))).select("id").all();
        if (users.length === 0) return { items: [], total: 0, page, limit };
        const userIds = users.map((u) => u.id);
        query = query.where((s) => s.userId.in(userIds));
    }

    const { total } = await query.aggregate((a) => ({ total: a.count() }));
    const rows = await query
        .orderBy([(s) => s.user.name.asc(), (s) => s.id.asc()])
        .include("user")
        .limit(limit)
        .offset((page - 1) * limit)
        .all();

    const counts = await completedCounts(rows.map((s) => s.id));
    const items = rows.map((s) => ({
        id: s.id,
        name: s.user.name,
        email: s.user.email,
        phone: s.phone,
        avatar: s.avatar,
        skills: s.skills,
        experienceYears: s.experienceYears,
        availability: s.availability,
        rating: s.rating,
        status: s.status,
        isActive: s.isActive,
        completedJobs: counts.get(s.id) ?? 0,
    }));
    return { items, total, page, limit };
}

// the full profile, plus the jobs this person is currently working on or has coming up
export async function getStaff(staffId: string, session: Session) {
    assertAdmin(session);

    const staff = await db.orm.public.Staff.where({ id: staffId }).include("user").first();
    if (!staff) throw new NotFoundError("Staff member not found");

    const counts = await completedCounts([staffId]);

    const unfinished = await db.orm.public.Booking
        .where((b) => b.status.notIn(["Completed", "Cancelled", "Rejected"]))
        .where((b) => b.assignments.some((a) => and(a.staffId.eq(staffId), a.status.neq("Rejected"))))
        .orderBy((b) => b.scheduledAt.asc())
        .include("customer")
        .include("assignments")
        .all();

    return {
        id: staff.id,
        name: staff.user.name,
        email: staff.user.email,
        phone: staff.phone,
        avatar: staff.avatar,
        skills: staff.skills.flatMap((id) => getServiceById(id) ?? []),
        experienceYears: staff.experienceYears,
        availability: staff.availability,
        rating: staff.rating,
        status: staff.status,
        isActive: staff.isActive,
        completedJobs: counts.get(staffId) ?? 0,
        currentJobs: unfinished.map((b) => ({
            id: b.id,
            scheduledAt: b.scheduledAt,
            status: b.status,
            customerName: b.customer.name,
            myStatus: b.assignments.find((a) => a.staffId === staffId)?.status,
        })),
    };
}

