// creates the login (User) and the profile (Staff) together. the autogenerated password is given once (to be noted down)
export async function createStaff(input: CreateStaffInput, session: Session) {
    assertAdmin(session);

    const email = input.email.toLowerCase();
    const password = generatePassword();
    const passwordHash = await hashPassword(password);

    return db.transaction(async (tx) => {
        const existing = await tx.orm.public.User.where({ email }).first();
        if (existing) throw new ConflictError("A user with this email already exists");

        const user = await tx.orm.public.User.create({ name: input.name, email, passwordHash, role: "staff" });
        const staff = await tx.orm.public.Staff.create({
            phone: input.phone,
            avatar: input.avatar,
            skills: input.skills,
            experienceYears: input.experienceYears,
            availability: input.availability,
            rating: 0, // new staff have no ratings yet; a rating of 0 should show "no ratings yet" since ratings are otherwise limited to 1-5 (inclusive)
            status: "Available",
            isActive: true,
            userId: user.id,
        });

        return { id: staff.id, email, temporaryPassword: password };
    });
}

// edits the profile; name and email live in User, the rest in Staff
export async function updateStaff(staffId: string, input: UpdateStaffInput, session: Session): Promise<void> {
    assertAdmin(session);
    const { name, email, ...profile } = input;

    await db.transaction(async (tx) => {
        const staff = await tx.orm.public.Staff.where({ id: staffId }).first();
        if (!staff) throw new NotFoundError("Staff member not found");

        if (name !== undefined || email !== undefined) {
            const newEmail = email?.toLowerCase();
            if (newEmail) {
                const taken = await tx.orm.public.User.where({ email: newEmail }).first();
                if (taken && taken.id !== staff.userId) throw new ConflictError("A user with this email already exists");
            }
            await tx.orm.public.User.where({ id: staff.userId }).update({
                ...(name !== undefined && { name }),
                ...(newEmail !== undefined && { email: newEmail }),
            });
        }

        if (Object.keys(profile).length > 0) {
            await tx.orm.public.Staff.where({ id: staffId }).update(profile);
        }
    });
}

// activate or deactivate, deactivating is blocked while the person has unfinished jobs
export async function setStaffActive(staffId: string, active: boolean, session: Session): Promise<void> {
    assertAdmin(session);

    await db.transaction(async (tx) => {
        const staff = await tx.orm.public.Staff.where({ id: staffId }).first();
        if (!staff) throw new NotFoundError("Staff member not found");

        if (!active) {
            const blocking = await tx.orm.public.Booking
                .where((b) => b.status.notIn(["Completed", "Cancelled", "Rejected"]))
                .where((b) => b.assignments.some((a) => and(a.staffId.eq(staffId), a.status.in(["Accepted", "On the Way"]))))
                .all();
            if (blocking.length > 0) {
                throw new ConflictError(
                    `Cannot deactivate: ${blocking.length} unfinished job(s) accepted (${blocking.map((b) => b.id).join(", ")})`
                );
            }
        }

        await tx.orm.public.Staff.where({ id: staffId }).update({ isActive: active });
    });
}

