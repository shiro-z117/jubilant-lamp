// autogenerates a password: 12 chars no symbols or spaces and no lookalike characters
const PASSWORD_CHARS = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
function generatePassword(length = 12): string {
    return Array.from({ length }, () => PASSWORD_CHARS[randomInt(PASSWORD_CHARS.length)]).join("");
}

// completed jobs are derived from bookings
async function completedCounts(staffIds: string[]): Promise<Map<string, number>> {
    const counts = new Map<string, number>();
    if (staffIds.length === 0) return counts;

    const done = await db.orm.public.Booking
        .where({ status: "Completed" })
        .where((b) => b.assignments.some((a) => and(a.staffId.in(staffIds), a.status.in(["Accepted", "On the Way"]))))
        .include("assignments")
        .all();

    for (const booking of done) {
        for (const a of booking.assignments) {
            if (staffIds.includes(a.staffId) && (a.status === "Accepted" || a.status === "On the Way")) {
                counts.set(a.staffId, (counts.get(a.staffId) ?? 0) + 1);
            }
        }
    }
    return counts;
}

